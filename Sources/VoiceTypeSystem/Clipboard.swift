import AppKit

/// Full multi-item, multi-type copy of the user's clipboard.
public struct PasteboardSnapshot: Equatable {
    public struct Entry: Equatable {
        public let type: NSPasteboard.PasteboardType
        public let data: Data
    }
    public let items: [[Entry]]

    /// Returns nil when any representation cannot be read (e.g. unresolved promises): paste is then skipped.
    public static func capture(_ pasteboard: NSPasteboard) -> PasteboardSnapshot? {
        var items: [[Entry]] = []
        for item in pasteboard.pasteboardItems ?? [] {
            var entries: [Entry] = []
            for type in item.types {
                guard let data = item.data(forType: type) else { return nil }
                entries.append(Entry(type: type, data: data))
            }
            items.append(entries)
        }
        return PasteboardSnapshot(items: items)
    }

    @discardableResult public func restore(to pasteboard: NSPasteboard) -> Bool {
        pasteboard.clearContents()
        guard !items.isEmpty else { return true }
        let objects = items.map { entries -> NSPasteboardItem in
            let item = NSPasteboardItem()
            entries.forEach { item.setData($0.data, forType: $0.type) }
            return item
        }
        return pasteboard.writeObjects(objects)
    }
}

public enum PasteboardRestoreOutcome: String, Codable { case restored, skippedChanged, failed, superseded }

/// Owns VoiceType's clipboard writes and the independent 500ms version-checked restore.
public final class ClipboardManager {
    public typealias Delay = (TimeInterval, @escaping () -> Void) -> Void
    public static let transientMarkers = [NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
                                          NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")]
    public static let restoreDelay: TimeInterval = 0.5

    private struct Pending { let id: UInt64; let snapshot: PasteboardSnapshot; let owned: Int }
    public let pasteboard: NSPasteboard
    private let delay: Delay
    private var pending: Pending?
    private var nextID: UInt64 = 0
    public var onRestore: ((PasteboardRestoreOutcome) -> Void)?

    public init(pasteboard: NSPasteboard = .general,
                delay: @escaping Delay = { seconds, work in DispatchQueue.main.asyncAfter(deadline: .now() + seconds, execute: work) }) {
        self.pasteboard = pasteboard; self.delay = delay
    }

    /// If our previous paste text is still on the clipboard, the true original is the earlier saved snapshot.
    public func captureOriginal() -> PasteboardSnapshot? {
        if let pending = pending, pasteboard.changeCount == pending.owned { return pending.snapshot }
        return PasteboardSnapshot.capture(pasteboard)
    }

    /// Writes text for one automatic Cmd+V and returns the owned version.
    public func writeForPaste(_ text: String) -> Int? {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        Self.transientMarkers.forEach { item.setData(Data(), forType: $0) }
        guard pasteboard.writeObjects([item]) else { return nil }
        return pasteboard.changeCount
    }

    /// Copy-only delivery: stays on the clipboard for the user; never auto-restored.
    public func writeForManualPaste(_ text: String) -> Bool {
        pasteboard.clearContents()
        return pasteboard.setString(text, forType: .string) && pasteboard.string(forType: .string) == text
    }

    @discardableResult public func scheduleRestore(_ snapshot: PasteboardSnapshot, owned: Int) -> UInt64 {
        nextID += 1
        let id = nextID
        if pending != nil { onRestore?(.superseded) }
        pending = Pending(id: id, snapshot: snapshot, owned: owned)
        delay(Self.restoreDelay) { [weak self] in self?.performRestore(id) }
        return id
    }

    /// Restores only if the clipboard still holds exactly the version VoiceType wrote.
    public func performRestore(_ id: UInt64) {
        guard let pending = pending, pending.id == id else { return }
        self.pending = nil
        guard pasteboard.changeCount == pending.owned else { onRestore?(.skippedChanged); return }
        onRestore?(pending.snapshot.restore(to: pasteboard) ? .restored : .failed)
    }

    public var hasPendingRestore: Bool { pending != nil }
}
